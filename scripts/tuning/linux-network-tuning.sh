#!/usr/bin/env bash
#
# linux network tuning for linebridge deployments
#
# the gateway holds a long lived tcp connection per client and the api
# server proxies requests over unix sockets and nats, both roles benefit
# from a larger accept queue, larger socket buffers and sane keepalive
#
# usage:
#   sudo ./linux-network-tuning.sh apply [--role gateway|server|all] [--bbr] [--no-limits]
#   ./linux-network-tuning.sh check
#   sudo ./linux-network-tuning.sh revert
#
# the script is idempotent, apply writes a single sysctl drop-in and
# reloads it, revert removes only that drop-in
#
set -euo pipefail

SYSCTL_FILE="/etc/sysctl.d/99-linebridge-ws.conf"
LIMITS_FILE="/etc/security/limits.d/99-linebridge-ws.conf"
SYSTEMD_FILE="/etc/systemd/system.conf.d/99-linebridge-ws.conf"
NOFILE_LIMIT=1048576

MODE="${1:-apply}"
shift || true

ROLE="all"
ENABLE_BBR=false
APPLY_LIMITS=true

while [ $# -gt 0 ]; do
	case "$1" in
	--role)
		ROLE="${2:-all}"
		shift 2
		;;
	--bbr)
		ENABLE_BBR=true
		shift
		;;
	--no-limits)
		APPLY_LIMITS=false
		shift
		;;
	*)
		echo "unknown option: $1" >&2
		exit 1
		;;
	esac
done

case "$ROLE" in
gateway | server | all) ;;
*)
	echo "invalid role: $ROLE (expected gateway, server or all)" >&2
	exit 1
	;;
esac

RED=$'\033[0;31m'
GREEN=$'\033[0;32m'
YELLOW=$'\033[1;33m'
NC=$'\033[0m'

info() { printf '%s[info]%s %s\n' "$GREEN" "$NC" "$1"; }
warn() { printf '%s[warn]%s %s\n' "$YELLOW" "$NC" "$1"; }
error() { printf '%s[error]%s %s\n' "$RED" "$NC" "$1" >&2; }

require_root() {
	if [ "$(id -u)" -ne 0 ]; then
		error "this action needs root"
		exit 1
	fi
}

in_container() {
	[ -f /.dockerenv ] || grep -qa "docker\|containerd\|kubepods" /proc/1/cgroup 2>/dev/null
}

generate_sysctl_file() {
	cat <<EOF
# generated by linebridge linux-network-tuning.sh (role: $ROLE)
# do not edit manually, rerun the script instead

# backlog for new connections, the gateway accepts a burst on reconnect
net.core.somaxconn = 65535
net.core.netdev_max_backlog = 65535
net.ipv4.tcp_max_syn_backlog = 65535
net.ipv4.tcp_syncookies = 1

# socket buffers sized for thousands of concurrent websocket frames
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
net.core.optmem_max = 65536
net.ipv4.tcp_rmem = 4096 87380 16777216
net.ipv4.tcp_wmem = 4096 65536 16777216

# keep idle tcp sessions healthy without relying only on ws heartbeats
# probes are cheap and detect dead peers behind nat or a load balancer
net.ipv4.tcp_keepalive_time = 60
net.ipv4.tcp_keepalive_intvl = 10
net.ipv4.tcp_keepalive_probes = 6

# faster reuse of closed sockets, important for proxying and nats reconnects
net.ipv4.tcp_fin_timeout = 15
net.ipv4.tcp_tw_reuse = 1
net.ipv4.tcp_max_tw_buckets = 262144
net.ipv4.ip_local_port_range = 10240 65000

# latency for small interactive frames
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_mtu_probing = 1

# file descriptors available to the process
fs.file-max = 2097152
fs.nr_open = 2097152

# avoid swapping the go and node heaps under memory pressure
vm.swappiness = 10
EOF

	if [ "$ENABLE_BBR" = true ]; then
		cat <<EOF

# low latency queueing with bbr
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
EOF
	fi
}

apply_limits() {
	info "writing $LIMITS_FILE"

	cat >"$LIMITS_FILE" <<EOF
# generated by linebridge linux-network-tuning.sh
root soft nofile $NOFILE_LIMIT
root hard nofile $NOFILE_LIMIT
* soft nofile $NOFILE_LIMIT
* hard nofile $NOFILE_LIMIT
EOF

	if command -v systemctl >/dev/null 2>&1 && [ -d /etc/systemd ]; then
		mkdir -p "$(dirname "$SYSTEMD_FILE")"

		cat >"$SYSTEMD_FILE" <<EOF
# generated by linebridge linux-network-tuning.sh
[Manager]
DefaultLimitNOFILE=$NOFILE_LIMIT
EOF

		warn "systemd limits need 'systemctl daemon-reexec' to take effect for new services"
	fi
}

print_runtime_notes() {
	local total_mem_mb
	total_mem_mb=$(awk '/MemTotal/ {printf "%d", $2 / 1024}' /proc/meminfo)

	echo
	info "runtime notes (visible memory: ${total_mem_mb}MB)"
	echo "  gateway (go):"
	echo "    GOMEMLIMIT=<75% of the container limit, e.g. 1536MiB>"
	echo "    GOGC=100 (default), keep GOMAXPROCS at the container cpu limit"
	echo "  server (node):"
	echo "    NODE_OPTIONS=--max-old-space-size=<75% of the container limit in MB>"
	echo "  containers:"
	echo "    nofile ulimit must be raised inside the container too:"
	echo "      docker run --ulimit nofile=$NOFILE_LIMIT:$NOFILE_LIMIT ..."
	echo "      or ulimits.nofile in docker compose"
	echo
	echo "  websocket tuning (gateway env):"
	echo "    WS_PING_INTERVAL=15    seconds between server pings"
	echo "    WS_PING_WAIT=30        extra window before a silent peer is evicted"
	echo "    WS_WRITE_TIMEOUT=15    per frame write deadline"
	echo "    WS_READ_BUFFER_SIZE=4096"
	echo "    WS_MAX_TOPICS_PER_CONN=256"
	echo "    PRESENCE_TTL=90            presence key ttl in seconds"
	echo "    PRESENCE_REFRESH_INTERVAL=30  presence refresh period in seconds"
}

do_apply() {
	require_root

	if in_container; then
		warn "container detected, /proc/sys is usually read only here"
		warn "run this script on the host or pass the values through the orchestrator"
	fi

	info "writing $SYSCTL_FILE"
	generate_sysctl_file >"$SYSCTL_FILE"

	if sysctl --system >/dev/null 2>&1; then
		info "sysctl values applied"
	else
		warn "sysctl --system reported an error, check the values with 'sysctl -a'"
	fi

	if [ "$APPLY_LIMITS" = true ]; then
		apply_limits
	fi

	echo
	do_check
	print_runtime_notes
}

do_revert() {
	require_root

	for file in "$SYSCTL_FILE" "$LIMITS_FILE" "$SYSTEMD_FILE"; do
		if [ -f "$file" ]; then
			rm -f "$file"
			info "removed $file"
		fi
	done

	sysctl --system >/dev/null 2>&1 || true

	warn "a daemon-reexec is needed to drop systemd limits: systemctl daemon-reexec"
}

check_value() {
	local key="$1"
	local expected="$2"
	local current

	current=$(sysctl -n "$key" 2>/dev/null || echo "unavailable")

	if [ "$current" = "unavailable" ]; then
		warn "$key: $current"
		return
	fi

	if [ "$current" = "$expected" ]; then
		printf '  %sok%s   %s = %s\n' "$GREEN" "$NC" "$key" "$current"
	else
		printf '  %sdiff%s %s = %s (recommended %s)\n' "$YELLOW" "$NC" "$key" "$current" "$expected"
	fi
}

do_check() {
	printf '\n'
	info "current kernel values"
	printf '  a diff means the running value differs from the recommendation\n'

	check_value net.core.somaxconn 65535
	check_value net.core.netdev_max_backlog 65535
	check_value net.ipv4.tcp_max_syn_backlog 65535
	check_value net.ipv4.tcp_keepalive_time 60
	check_value net.ipv4.tcp_keepalive_intvl 10
	check_value net.ipv4.tcp_keepalive_probes 6
	check_value net.ipv4.tcp_fin_timeout 15
	check_value net.ipv4.tcp_tw_reuse 1
	check_value net.ipv4.tcp_max_tw_buckets 262144
	check_value net.ipv4.tcp_slow_start_after_idle 0
	check_value net.ipv4.tcp_mtu_probing 1
	check_value fs.file-max 2097152
	check_value fs.nr_open 2097152
	check_value vm.swappiness 10

	echo
	echo "  net.ipv4.ip_local_port_range = $(sysctl -n net.ipv4.ip_local_port_range 2>/dev/null || echo unavailable)"
	echo "  net.core.rmem_max = $(sysctl -n net.core.rmem_max 2>/dev/null || echo unavailable)"
	echo "  net.core.wmem_max = $(sysctl -n net.core.wmem_max 2>/dev/null || echo unavailable)"
	echo "  net.ipv4.tcp_congestion_control = $(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null || echo unavailable)"
	echo "  net.core.default_qdisc = $(sysctl -n net.core.default_qdisc 2>/dev/null || echo unavailable)"
	echo "  max open files (this shell) = $(ulimit -n)"
}

case "$MODE" in
apply) do_apply ;;
check) do_check ;;
revert) do_revert ;;
*)
	echo "usage: $0 [apply|check|revert] [--role gateway|server|all] [--bbr] [--no-limits]" >&2
	exit 1
	;;
esac
